class LegalKnowledgeBaseManager {
  private articles: Map<string, LegalArticle> = new Map();

  constructor() {
    for (const article of INITIAL_LEGAL_ARTICLES) {
      this.articles.set(article.id, article);
    }
  }

  public getAllArticles(): LegalArticle[] {
    return Array.from(this.articles.values());
  }

  public getArticleById(id: string): LegalArticle | undefined {
    return this.articles.get(id);
  }

  public getArticlesByCategory(category: string): LegalArticle[] {
    return this.getAllArticles().filter((a) => a.category.includes(category) || category.includes(a.category));
  }

  public ingestDocument(payload: IngestDocumentPayload): { added: number; updated: number } {
    let added = 0;
    let updated = 0;

    for (const item of payload.articles) {
      const id = `${payload.category}_${item.articleNumber}`.replace(/[\s\/\\]+/g, '_');
      const isExisting = this.articles.has(id);

      const article: LegalArticle = {
        id,
        lawId: `law_${payload.category}`,
        lawTitle: payload.lawTitle,
        category: payload.category,
        articleNumber: item.articleNumber,
        title: item.title,
        content: item.content,
        notes: item.notes || [],
        approvalDate: item.approvalDate,
        effectiveDate: item.effectiveDate,
        validityStatus: item.validityStatus || 'in_force',
        validityStatusLabel: item.validityStatus === 'amended' ? 'اصلاح‌شده' : item.validityStatus === 'repealed' ? 'منسوخ' : 'معتبر و لازم‌الاجرا',
        officialSource: item.officialSource || 'سامانه ملی قوانین و مقررات جمهوری اسلامی ایران',
        officialUrl: item.officialUrl,
        lastVerifiedDate: new Date().toLocaleDateString('fa-IR'),
        keywords: item.keywords || [item.articleNumber, item.title, payload.lawTitle]
      };

      this.articles.set(id, article);
      if (isExisting) {
        updated++;
      } else {
        added++;
      }
    }

    return { added, updated };
  }

  public getStats() {
    const total = this.articles.size;
    const categories = new Set(this.getAllArticles().map((a) => a.category));
    return {
      totalArticles: total,
      categoriesCount: categories.size,
      categoriesList: Array.from(categories),
      lastSyncDate: '۱۴۰۳/۰۸/۱۵'
    };
  }
}

export const knowledgeBase = new LegalKnowledgeBaseManager();
